import {readFileSync,writeFileSync} from 'node:fs'
import sharp from 'sharp'
import {createElement} from 'react'
import {renderToStaticMarkup} from 'react-dom/server'
import {Minus,Plus,Volume2,VolumeX,Mic,MicOff,Check} from 'lucide-react'
import {Resvg} from '@resvg/resvg-js'

// Player icons retain their colours over artwork; hearts use tintable alpha masks.
// Heart path from Lucide (ISC), matching the browser's installed icon.
const heart = 'M2 9.5a5.5 5.5 0 0 1 9.591-3.676.56.56 0 0 0 .818 0A5.49 5.49 0 0 1 22 9.5c0 2.29-1.5 4-3 5.5l-5.492 5.313a2 2 0 0 1-3 .019L5 15c-1.5-1.5-3-3.2-3-5.5'
const audioShape=icon=>renderToStaticMarkup(createElement(icon,{color:'white'})).replace(/^<svg[^>]*>/,'<g fill="none" stroke="white" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">').replace(/<\/svg>$/,'</g>')
const shapes = {
  spotify: '<circle cx="12" cy="12" r="11" fill="#1ed760"/><path d="M5.5 9c4.5-1.4 8.9-1 13 1.2M6.3 12.5c3.6-1.1 7.6-.8 10.8 1M7.2 15.7c3-.8 5.9-.6 8.7.9" stroke="black" stroke-width="1.7" stroke-linecap="round"/>',
  roon: null,
  apple_music: null,
  audio_check: audioShape(Check),
  audio_minus: audioShape(Minus),
  audio_plus: audioShape(Plus),
  audio_speaker: audioShape(Volume2),
  audio_muted: audioShape(VolumeX),
  audio_mic: audioShape(Mic),
  audio_mic_muted: audioShape(MicOff),
  heart: `<path d="${heart}" stroke="white" stroke-width="2" stroke-linejoin="round"/>`,
  heart_filled: `<path d="${heart}" fill="white"/>`,
}
const license=readFileSync(new URL('../../node_modules/lucide-react/LICENSE',import.meta.url),'utf8').split('\n---')[0]
const output=['/*\n'+license+'*/', '// Generated by firmware/tools/build-music-badges.mjs.', '#pragma once', '#include "lvgl.h"']
for(const [name,shape] of Object.entries(shapes)) {
  const player=name==='roon'||name==='spotify'||name==='apple_music'
  const size=player?30:name.startsWith('audio_')?96:20
  const rgba=shape===null
    ? await sharp(readFileSync(new URL(`../../public/icons/players/${name==='apple_music'?'apple-music':name}.png`,import.meta.url))).resize(size,size).ensureAlpha().raw().toBuffer()
    : new Resvg(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none">${shape}</svg>`,{fitTo:{mode:'width',value:size}}).render().pixels
  const pixels=player?Array.from({length:size*size*4},(_,i)=>rgba[(i&~3)+[2,1,0,3][i%4]])
    :Array.from({length:size*size},(_,i)=>Math.round(rgba[i*4]*rgba[i*4+3]/255))
  const stride=size*(player?4:1)
  output.push(`static const uint8_t music_${name}_pixels[${pixels.length}] = {${pixels.join(',')}};`,
    `static const lv_image_dsc_t music_${name} = { .header={.magic=LV_IMAGE_HEADER_MAGIC,.cf=${player?'LV_COLOR_FORMAT_ARGB8888':'LV_COLOR_FORMAT_A8'},.w=${size},.h=${size},.stride=${stride}},.data_size=${pixels.length},.data=music_${name}_pixels };`)

}
writeFileSync(new URL('../main/music_badge_icons.h',import.meta.url),output.join('\n')+'\n')
