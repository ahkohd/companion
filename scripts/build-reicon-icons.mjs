import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { Resvg } from '@resvg/resvg-js'

// 128px gives exact integer destination sizes with LVGL's 1/256 image scale.
// Keep the full SVG viewBox so the native and browser optical alignment agree.
const side = 128
const names = ['previous', 'next', 'play']
const root = new URL('../', import.meta.url)
const source = ['// Generated by scripts/build-reicon-icons.mjs from public/icons/reicon/*.svg.',
  '#include "reicon_icons.h"', '']
const header = ['// Generated by scripts/build-reicon-icons.mjs. Do not edit.',
  '#pragma once', '#include "lvgl.h"', '', `#define REICON_MASK_SIDE ${side}`, '']
for (const name of names) {
  const svg = readFileSync(new URL(`public/icons/reicon/${name}.svg`, root), 'utf8')
  const rendered = new Resvg(svg.replaceAll('currentColor', '#ffffff'), { fitTo: { mode: 'width', value: side } }).render()
  if (rendered.width !== side || rendered.height !== side) throw new Error(`Expected square ${name} SVG`)
  const rgba = rendered.pixels
  const alpha = Uint8Array.from({ length: side * side }, (_, index) => rgba[index * 4 + 3])
  source.push(`// SVG SHA-256: ${createHash('sha256').update(svg).digest('hex')}`,
    `static const uint8_t ${name}_alpha[${alpha.length}] = {`)
  for (let start = 0; start < alpha.length; start += 32) source.push(`    ${Array.from(alpha.subarray(start, start + 32)).join(',')},`)
  source.push('};', `const lv_image_dsc_t reicon_${name} = {`,
    '    .header = { .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_A8,',
    `        .w = ${side}, .h = ${side}, .stride = ${side} },`,
    `    .data_size = sizeof(${name}_alpha), .data = ${name}_alpha,`, '};', '')
  header.push(`extern const lv_image_dsc_t reicon_${name};`)
}
for (const [filename, lines] of [['reicon_icons.c', source], ['reicon_icons.h', header]]) {
  const output = `${lines.join('\n')}\n`
  const target = fileURLToPath(new URL(`firmware/main/${filename}`, root))
  if (process.argv.includes('--check')) {
    if (readFileSync(target, 'utf8') !== output) throw new Error('Regenerate native Reicon icons with node scripts/build-reicon-icons.mjs')
  } else writeFileSync(target, output)
}
