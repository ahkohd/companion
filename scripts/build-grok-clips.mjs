import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import catalog from '../shared/grok-catalog.json' with {type:'json'};
import {createCapture,GROK_STATES} from './grok-source/capture.mjs';
import {rasterSnapshot,WIDTH,HEIGHT} from './grok-render.mjs';
import {encodeFrame,decodeFrame} from './grok-codec.mjs';
const sha=data=>createHash('sha256').update(data).digest('hex');
const FPS=24,KEY=24,STATE_SECONDS=8,ACTION_SECONDS=8;
const inputs=['shared/grok-catalog.json','web/vendor/grok-bot/upstream-renderer.tsx','scripts/grok-source/capture.mjs','scripts/grok-render.mjs','scripts/grok-codec.mjs','scripts/build-grok-clips.mjs'];
const sourceHash=sha(Buffer.concat(await Promise.all(inputs.map(p=>readFile(p)))));
const output='public/grok';
await mkdir(output,{recursive:true});
if(JSON.stringify(catalog.filter(c=>c.group!=='Actions').map(c=>c.source))!==JSON.stringify(GROK_STATES))throw Error('Source state catalogue changed');
const only=process.argv.find(a=>a.startsWith('--only='))?.slice(7).split(',');
const stats=[];
for(const item of catalog.filter(c=>!only||only.includes(c.source))) {
  const count=FPS*(item.group==='Actions'?ACTION_SECONDS:STATE_SECONDS),loop=item.group==='Actions'?0xffffffff:FPS*4;
  const capture=createCapture(item.source),frames=[];
  for(let i=0;i<count;i++) {capture.advance((i+.5)/FPS);frames.push(rasterSnapshot(capture.snapshot()))}
  // Blend the last 400 ms into the frames immediately before the loop start.
  // Playback wraps to loopStart, so the next frame continues moving forward.
  if(loop!==0xffffffff)for(let n=0;n<10;n++) {
    const a=frames[count-10+n],b=frames[loop-10+n],mix=(n+1)/10;
    for(let j=0;j<a.length;j++) {
      let c=0;for(const [shift,mask] of [[11,31],[5,63],[0,31]])c|=Math.round(((a[j]>>shift)&mask)*(1-mix)+((b[j]>>shift)&mask)*mix)<<shift;
      a[j]=c;
    }
  }
  const reduced=createCapture(item.source,{reduced:true});reduced.advance(1);frames.push(rasterSnapshot(reduced.snapshot()));
  const blocks=[],decoded=new Uint16Array(WIDTH*HEIGHT),offsets=[];
  let offset=24+(count+2)*4;
  for(let i=0;i<frames.length;i++) {
    const key=i===count||i%KEY===0;
    if(key)decoded.fill(0);
    const block=encodeFrame(frames[i],key?null:frames[i-1],WIDTH);
    if(!decodeFrame(block,decoded)||!Buffer.from(decoded.buffer).equals(Buffer.from(frames[i].buffer)))throw Error(`${item.source} frame ${i} failed round trip`);
    offsets.push(offset);blocks.push(block);offset+=block.length;
  }
  offsets.push(offset);
  const header=Buffer.alloc(24+(count+2)*4);
  header.write('GRC1');header.writeUInt16LE(WIDTH,4);header.writeUInt16LE(HEIGHT,6);header.writeUInt16LE(FPS,8);header.writeUInt16LE(KEY,10);
  header.writeUInt32LE(count,12);header.writeUInt32LE(loop,16);header.writeUInt32LE(count,20);
  offsets.forEach((value,i)=>header.writeUInt32LE(value,24+i*4));
  const data=Buffer.concat([header,...blocks]);
  await writeFile(`${output}/${item.source}.bin`,data);
  const record={id:item.id,frames:count,loop,bytes:data.length,sha256:sha(data)};
  stats.push(record);console.log(`${item.source}: ${count} frames, ${(data.length/1024).toFixed(0)} KB`);
}
if(only)process.exit(0);
let offset=0;
const chunks=await Promise.all(catalog.map(c=>readFile(`${output}/${c.source}.bin`)));
const lines=catalog.map((c,i)=>{const line=`    {"${c.id}", ${offset}u, ${chunks[i].length}u},`;offset+=chunks[i].length;return line});
const pack=Buffer.concat(chunks);
await writeFile('firmware/main/grok_clips.bin',pack);
await writeFile('firmware/main/grok_catalog.h',`/* Generated by scripts/build-grok-clips.mjs. */\n#define GROK_CLIP_COUNT ${catalog.length}\nstatic const struct { const char *id; uint32_t offset, length; } GROK_CLIPS[GROK_CLIP_COUNT] = {\n${lines.join('\n')}\n};\n`);
await writeFile('shared/grok-manifest.json',JSON.stringify({version:1,sourceHash,inputs,width:WIDTH,height:HEIGHT,fps:FPS,key:KEY,bytes:pack.length,sha256:sha(pack),clips:stats},null,2)+'\n');
console.log(`All ${catalog.length} animations: ${(pack.length/1024/1024).toFixed(2)} MB`);
