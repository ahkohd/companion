import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import schema from '../shared/design-schema.json' with { type: 'json' }

const modules = ['face', 'usage', 'hey', 'clock', 'roon', 'audio', 'speedDial']
const lines = ['// Generated by scripts/build-design-schema.mjs from shared/design-schema.json.', '#pragma once', '#include <stdbool.h>', '#include <stdint.h>', '']
for (const id of modules) {
  lines.push('typedef struct {', ...schema[id].map(field => `    int32_t ${field.key};`), `} ${id}_design_t;`, '')
}
lines.push('typedef union {', ...modules.map(id => `    ${id}_design_t ${id};`), `    int32_t values[${Math.max(...modules.map(id => schema[id].length))}];`, '} module_design_t;', '')
lines.push('static inline unsigned module_design_length(unsigned kind)', '{', '    switch (kind) {', ...modules.map((id, index) => `        case ${index}: return ${schema[id].length};`), '        default: return 0;', '    }', '}', '')
lines.push('static inline void module_design_default(unsigned kind, module_design_t *out)', '{', '    *out = (module_design_t){0};', '    switch (kind) {')
modules.forEach((id, index) => lines.push(`        case ${index}: out->${id} = (${id}_design_t){`, ...schema[id].map(field => `            .${field.key} = ${field.default},`), '        }; break;'))
lines.push('    }', '}', '')
lines.push('static inline bool module_design_valid(unsigned kind, unsigned field, int32_t value)', '{', '    switch (kind) {')
modules.forEach((id, index) => {
  lines.push(`        case ${index}: switch (field) {`)
  schema[id].forEach((field, offset) => lines.push(`            case ${offset}: return ${field.allowAuto ? 'value == 0 || ' : ''}${field.options ? field.options.map(option => `value == ${option}`).join(' || ') : `(value >= ${field.min} && value <= ${field.max})`};`))
  lines.push('            default: return false;', '        }')
})
lines.push('        default: return false;', '    }', '}', '')
const output = lines.join('\n')
const target = fileURLToPath(new URL('../firmware/main/module_design.h', import.meta.url))
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) throw new Error('Regenerate native design schema with node scripts/build-design-schema.mjs')
} else writeFileSync(target, output)
